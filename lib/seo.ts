import type { Metadata } from "next";

/**
 * Single source of truth for search-engine metadata.
 *
 * Every public page builds its metadata through `pageMetadata` so titles,
 * canonical URLs and social cards stay consistent. Private app pages use
 * `privatePageMetadata`, which marks them `noindex` — they are behind a login,
 * so a search result for them only ever wastes a visitor's click.
 */

export const SITE_URL = "https://hiremind.co.in";
/**
 * The one canonical form of the home URL — canonical, og:url, sitemap and JSON-LD all use it.
 * No trailing slash, because Next.js always emits the root canonical without one.
 */
export const HOME_URL = SITE_URL;
export const SITE_NAME = "HireMind";
export const SITE_TAGLINE = "Intelligent Hiring. Trusted Future.";

/** Used verbatim as the home page description and as the fallback everywhere else. */
export const SITE_DESCRIPTION =
  "HireMind is an AI-powered recruitment platform. Recruiters and hiring agencies match candidates to jobs, parse resumes and screen applicants automatically, while job seekers find genuine, verified openings.";

export const SITE_LOCALE = "en_IN";

/**
 * Generated by app/opengraph-image.tsx. Set explicitly because a page-level `openGraph`
 * object replaces the inherited one, which silently dropped og:image before.
 */
export const OG_IMAGE = {
  url: `${SITE_URL}/opengraph-image`,
  width: 1200,
  height: 630,
  alt: "HireMind AI recruitment software dashboard showing candidate match scores",
};

type PageSeoInput = {
  /** Page title without the brand suffix — the root template appends it. */
  title: string;
  description: string;
  /** Route path, e.g. "/features". Use "/" for the home page. */
  path: string;
};

function absoluteUrl(path: string): string {
  return path === "/" ? HOME_URL : `${SITE_URL}${path}`;
}

/** Metadata for a public, indexable page. */
export function pageMetadata({ title, description, path }: PageSeoInput): Metadata {
  const socialTitle = `${title} - ${SITE_NAME}`;
  return {
    title,
    description,
    alternates: { canonical: absoluteUrl(path) },
    openGraph: {
      type: "website",
      siteName: SITE_NAME,
      locale: SITE_LOCALE,
      url: absoluteUrl(path),
      title: socialTitle,
      description,
      images: [OG_IMAGE],
    },
    twitter: {
      card: "summary_large_image",
      title: socialTitle,
      description,
      images: [OG_IMAGE.url],
    },
  };
}

/** Metadata for a page that must never appear in search results. */
export function privatePageMetadata(title: string): Metadata {
  return {
    title,
    robots: { index: false, follow: false },
  };
}
