/** Every IANA zone the browser knows, labelled with its current GMT offset. */
export function allTimeZones(): string[] {
  const supported = (Intl as { supportedValuesOf?: (k: string) => string[] }).supportedValuesOf;
  const zones = typeof supported === "function" ? supported("timeZone") : Object.values(TIME_ZONE_BY_COUNTRY);
  return [...new Set(zones)].sort().map(labelForZone);
}

/** "Asia/Kolkata" → "(GMT +05:30) Asia/Kolkata". */
export function labelForZone(zone: string): string {
  try {
    const parts = new Intl.DateTimeFormat("en-GB", { timeZone: zone, timeZoneName: "longOffset" })
      .formatToParts(new Date());
    const raw = parts.find((p) => p.type === "timeZoneName")?.value ?? "GMT";
    const offset = raw.replace("GMT", "").trim() || "+00:00";
    return `(GMT ${offset}) ${zone}`;
  } catch {
    return zone;
  }
}

/**
 * Preselected zone for a company: its country's zone, else whatever the browser reports,
 * so the field is sensible before the admin touches it.
 */
export function defaultTimeZone(country: string): string {
  const zone = TIME_ZONE_BY_COUNTRY[country]
    ?? Intl.DateTimeFormat().resolvedOptions().timeZone
    ?? "UTC";
  return labelForZone(zone);
}
